CREATE TABLE IF NOT EXISTS official_market_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL DEFAULT '',
    platform VARCHAR(32) NOT NULL DEFAULT 'PC',
    server VARCHAR(80) NOT NULL DEFAULT 'All platforms',
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    price_unit VARCHAR(60) NOT NULL DEFAULT 'each',
    stock VARCHAR(100) NOT NULL DEFAULT 'Available',
    delivery_method VARCHAR(600) NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_official_market_products_public
    ON official_market_products (is_active, sort_order, created_at DESC);
