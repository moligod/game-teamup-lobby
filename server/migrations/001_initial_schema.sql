CREATE TABLE IF NOT EXISTS team_types (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    email TEXT,
    avatar TEXT,
    signature TEXT,
    role TEXT DEFAULT 'user',
    online_status TEXT,
    is_online BOOLEAN DEFAULT FALSE,
    oauth_provider TEXT,
    oauth_uid TEXT,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    team_type TEXT NOT NULL REFERENCES team_types(id),
    leader_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    current_members INTEGER DEFAULT 1,
    max_members INTEGER NOT NULL,
    min_combat_power INTEGER DEFAULT 0,
    status TEXT DEFAULT 'active',
    requires_approval BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS team_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT DEFAULT 'member',
    joined_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(team_id, user_id)
);

CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    status TEXT NOT NULL,
    content TEXT NOT NULL,
    timestamp TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS friends (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    friend_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status TEXT DEFAULT 'pending',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, friend_id)
);

CREATE TABLE IF NOT EXISTS team_types_i18n (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_type_id TEXT NOT NULL REFERENCES team_types(id) ON DELETE CASCADE,
    language TEXT NOT NULL,
    name TEXT NOT NULL,
    UNIQUE(team_type_id, language)
);

CREATE TABLE IF NOT EXISTS system_messages_i18n (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_key TEXT NOT NULL,
    language TEXT NOT NULL,
    content TEXT NOT NULL,
    UNIQUE(message_key, language)
);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT,
    is_secret BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS team_applications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status TEXT DEFAULT 'pending',
    applied_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ,
    processed_by INTEGER REFERENCES users(id),
    UNIQUE(team_id, user_id)
);

CREATE TABLE IF NOT EXISTS user_player_bindings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    player_name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS player_profession_combat (
    player_name TEXT PRIMARY KEY,
    knight INTEGER DEFAULT 0,
    gunslinger INTEGER DEFAULT 0,
    fae_trickster INTEGER DEFAULT 0,
    dracolyte INTEGER DEFAULT 0,
    neon_ninja INTEGER DEFAULT 0,
    candy_barbarian INTEGER DEFAULT 0,
    ice_sage INTEGER DEFAULT 0,
    shadow_hunter INTEGER DEFAULT 0,
    pirate_captain INTEGER DEFAULT 0,
    boomeranger INTEGER DEFAULT 0,
    tomb_raiser INTEGER DEFAULT 0,
    lunar_lancer INTEGER DEFAULT 0,
    revenant INTEGER DEFAULT 0,
    chloromancer INTEGER DEFAULT 0,
    dino_tamer INTEGER DEFAULT 0,
    vanguardian INTEGER DEFAULT 0,
    bard INTEGER DEFAULT 0,
    solarion INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS leaderboards (
    leaderboard_id TEXT PRIMARY KEY,
    leaderboard_type TEXT NOT NULL,
    leaderboard_key TEXT,
    leaderboard_name TEXT,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS leaderboard_entries (
    leaderboard_id TEXT NOT NULL REFERENCES leaderboards(leaderboard_id) ON DELETE CASCADE,
    entry_index INTEGER NOT NULL,
    rank INTEGER NOT NULL,
    player_name TEXT NOT NULL,
    score TEXT NOT NULL,
    mastery_level INTEGER,
    mastery_level_text TEXT,
    trove_mastery_level INTEGER,
    geode_mastery_level INTEGER,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (leaderboard_id, entry_index)
);

CREATE TABLE IF NOT EXISTS discord_announcements (
    message_id TEXT PRIMARY KEY,
    guild_id TEXT,
    channel_id TEXT NOT NULL,
    author_id TEXT,
    author_name TEXT,
    author_avatar_url TEXT,
    content TEXT,
    embeds JSONB DEFAULT '[]'::jsonb,
    attachments JSONB DEFAULT '[]'::jsonb,
    message_url TEXT,
    posted_at TIMESTAMPTZ NOT NULL,
    edited_at TIMESTAMPTZ,
    synced_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
