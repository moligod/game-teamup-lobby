CREATE TABLE IF NOT EXISTS market_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category VARCHAR(16) NOT NULL CHECK (category IN ('flux', 'items', 'boosting', 'accounts', 'codes')),
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1000) NOT NULL DEFAULT '',
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    price_unit VARCHAR(60) NOT NULL DEFAULT 'each',
    stock VARCHAR(100) NOT NULL DEFAULT 'Available',
    delivery_method VARCHAR(600) NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_market_listings_public
    ON market_listings (is_active, category, created_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_market_listings_seller
    ON market_listings (seller_id, created_at DESC, id DESC);
