CREATE TABLE IF NOT EXISTS dishonesty_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dishonest_qq VARCHAR(32),
    dishonest_player_name VARCHAR(80),
    reason VARCHAR(1000) NOT NULL,
    evidence_urls JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    reviewer_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT dishonesty_reports_identifier_check CHECK (
        dishonest_qq IS NOT NULL OR dishonest_player_name IS NOT NULL
    ),
    CONSTRAINT dishonesty_reports_evidence_check CHECK (
        jsonb_typeof(evidence_urls) = 'array' AND jsonb_array_length(evidence_urls) > 0
    ),
    CONSTRAINT dishonesty_reports_status_check CHECK (status IN ('pending', 'approved', 'rejected'))
);

CREATE INDEX IF NOT EXISTS idx_dishonesty_reports_public
    ON dishonesty_reports (status, reviewed_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_dishonesty_reports_review
    ON dishonesty_reports (status, created_at DESC, id DESC);
