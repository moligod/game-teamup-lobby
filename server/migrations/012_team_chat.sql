CREATE TABLE IF NOT EXISTS team_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    status TEXT NOT NULL,
    content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 200),
    reply_to_id INTEGER REFERENCES team_messages(id) ON DELETE SET NULL,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_team_messages_recent
    ON team_messages (team_id, timestamp DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_team_messages_reply_to
    ON team_messages (reply_to_id)
    WHERE reply_to_id IS NOT NULL;
