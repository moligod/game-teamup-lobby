CREATE TABLE IF NOT EXISTS qq_bot_groups (
    group_openid TEXT PRIMARY KEY,
    proactive_messages_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    last_event_type TEXT NOT NULL,
    last_event_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS qq_team_notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_openid TEXT NOT NULL REFERENCES qq_bot_groups(group_openid) ON DELETE CASCADE,
    team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    payload JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'sent')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    locked_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (group_openid, team_id)
);

CREATE INDEX IF NOT EXISTS idx_qq_team_notification_outbox_pending
    ON qq_team_notification_outbox (status, next_attempt_at, id);
