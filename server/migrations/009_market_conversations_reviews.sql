CREATE TABLE IF NOT EXISTS market_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES market_listings(id) ON DELETE CASCADE,
    buyer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    seller_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT market_conversations_distinct_participants CHECK (buyer_id <> seller_id),
    CONSTRAINT market_conversations_listing_buyer_key UNIQUE (listing_id, buyer_id)
);

CREATE INDEX IF NOT EXISTS idx_market_conversations_participants
    ON market_conversations (buyer_id, seller_id, last_message_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_market_conversations_seller
    ON market_conversations (seller_id, last_message_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS market_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES market_conversations(id) ON DELETE CASCADE,
    sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_market_messages_conversation
    ON market_messages (conversation_id, created_at ASC, id ASC);

CREATE TABLE IF NOT EXISTS market_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES market_conversations(id) ON DELETE CASCADE,
    buyer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    seller_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating IN (-1, 1)),
    comment VARCHAR(1000) NOT NULL,
    image_urls JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(image_urls) = 'array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT market_reviews_conversation_key UNIQUE (conversation_id)
);

CREATE INDEX IF NOT EXISTS idx_market_reviews_seller
    ON market_reviews (seller_id, created_at DESC, id DESC);
